"""Prospective Stage-B native caller; requires frozen pins and explicit run scope.

This module adds no default, tune path, saving route or alternate cleanup owner.
The public CLI is the only production factory boundary; software tests supply
entirely fake IO and owners. No live manifest is generated by this implementation.
"""
from __future__ import annotations

from datetime import datetime,timezone
from pathlib import Path
import time
from typing import Any,Callable
import uuid

from inferenceos.tune.lookup_answer_publication import VERSION,CallerLedger,OwnedAnswerOutput,sha
from inferenceos.tune.lookup_answers_collect import collect_answers,NativeExecution
from inferenceos.tune.lookup_answers_manifest import AnswerManifest,AnswerPreflight,parse_answer_manifest
from inferenceos.tune.lookup_answers_native import NativeAnswerEngine
from inferenceos.tune.lookup_corpus import digest
from inferenceos.tune.lookup_fit import FitRefused,strict_json
from inferenceos.tune.lookup_fit_io import bounded_file_bytes,bounded_read


def load_inputs(root: Path,rules: Path,rules_sha: str) -> Any:
    from inferenceos.tune.lookup_answers_manifest import _local_path
    raw=bounded_file_bytes(rules,maximum_bytes=64*1024*1024)
    if sha(raw)!=rules_sha:raise FitRefused('Stage-B rules hash differs; zero backend constructions')
    manifest=AnswerManifest.model_validate_json(__import__('json').dumps(strict_json(raw),allow_nan=False))
    names=('proposal','protocol_document','stage_a_manifest','stage_a_record','stage_a_audit','stage_a_review')
    artifacts={getattr(manifest,k).path:bounded_file_bytes(_local_path(root,getattr(manifest,k).path),maximum_bytes=64*1024*1024) for k in names}
    return parse_answer_manifest(raw,artifacts)


def run_native(*,root: Path,settings: Any,rules: Path,rules_sha: str,out: Path,owner_authorized: bool,
               preflight_factory: Callable[...,Any],fit_engine_factory: Callable[...,Any],power: Callable[[],str],
               clock: Callable[[],int]=time.perf_counter_ns,rest: Callable[[int],None]=time.sleep,
               input_loader: Callable[...,Any]=load_inputs,execution_id: str | None=None) -> int:
    if owner_authorized is not True:raise FitRefused('separate owner Stage-B authorization is required')
    run_id=execution_id or uuid.uuid4().hex
    ledger=CallerLedger(run_id,clock)
    owned: OwnedAnswerOutput | None=None;engine: NativeAnswerEngine | None=None;preflight=None;inputs=None
    core=None;provenance=None;preservation=None;initial_power=None;final_cleanup=None
    pending: BaseException | None=None;problem=None;status='refused';code=4;prepared=False

    def remember(exc: BaseException) -> None:
        nonlocal pending,problem
        problem=dict(type=type(exc).__name__,message=str(exc))
        if pending is None or isinstance(exc,(KeyboardInterrupt,SystemExit)):
            if pending is not None:exc.__context__=pending
            pending=exc

    try:
        with ledger.measure('whole-job') as job:
            try:
                with ledger.measure('initial-output'):
                    owned=OwnedAnswerOutput(out,run_id)
                with ledger.measure('initial-validation'):
                    inputs=bounded_read(lambda:input_loader(root,rules,rules_sha),timeout_s=120)
                    initial_power=power()
                    if initial_power!='ac':raise FitRefused('initial AC required; zero backend constructions')
                    preflight=bounded_read(lambda:AnswerPreflight(root,settings,inputs,rules,rules_sha,
                                                                  preflight_factory=preflight_factory),timeout_s=120)
                    provenance=inputs.provenance();scope=inputs.derived_scope()
                with ledger.measure('engine-construction'):
                    # Native backend construction follows ALL model/source/provenance refusals.
                    engine=NativeAnswerEngine(fit_engine_factory(preflight),inputs.manifest.models)
                def guard() -> None:
                    assert owned is not None and preflight is not None
                    owned.verify()
                    bounded_read(preflight.check,timeout_s=30)
                execution=NativeExecution(run_id,rules_sha,digest(scope),job['start_ns'],True)
                with ledger.measure('execution'):
                    core=collect_answers(engine,scope,run_id=run_id,clock=clock,power=power,guard=guard,
                                         rest=rest,checkpoint=owned,simulated=False,execution=execution,boundary=ledger.measure)
                status=core['status'];code=0 if status=='done' else 2
            except BaseException as exc:
                remember(exc);status='interrupted' if isinstance(exc,(KeyboardInterrupt,SystemExit)) else 'refused' if isinstance(exc,(ValueError,OSError,LookupError)) else 'error'
                code=4 if status=='refused' else 3
            finally:
                if engine is not None:
                    try:
                        with ledger.measure('final-cleanup'):
                            final_cleanup=engine.retry_held()
                            if final_cleanup is not None:
                                status='stopped-cleanup';code=2
                    except BaseException as exc:
                        remember(exc);status='stopped-cleanup';code=2
                if preflight is not None:
                    try:
                        with ledger.measure('preservation'):
                            preservation=bounded_read(preflight.preservation,timeout_s=120)
                    except BaseException as exc:
                        remember(exc);status='changed-input-or-data';code=6
                if owned is not None:
                    if core is None:
                        try:core=owned.memory_diagnostic() or (owned.latest() if owned.sequence else None)
                        except BaseException as exc:remember(exc);code=7;status='checkpoint-unreadable'
                    envelope=dict(version=VERSION,run_id=run_id,simulated=False,manifest_sha256=rules_sha,
                                  status='collected-pending-closure' if status=='done' else status,
                                  provenance=provenance,core=core,preservation=preservation,initial_power=initial_power,
                                  final_cleanup=final_cleanup,error=problem,finished_at=datetime.now(timezone.utc).isoformat(),
                                  actual_qualification=False,automatic_admission=False,deployment_allowed=False)
                    try:
                        with ledger.measure('final-publication'):
                            envelope['caller_intervals']=ledger.snapshot()
                            owned.publish(envelope)
                        if owned.sequence:
                            with ledger.measure('closure-validation'):owned.prepare_closure()
                            prepared=True
                    except BaseException as exc:
                        remember(exc);code=7;status='publication-failed'
                if status!='done':job['outcome']='failed'
        if owned is not None and prepared:
            try:owned.seal(status=status,caller_intervals=ledger.snapshot(),manifest_sha256=rules_sha)
            except BaseException as exc:remember(exc);code=7
    finally:
        if owned is not None:
            try:owned.close()
            except BaseException as exc:
                # File-close errors must not replace an earlier Ctrl+C. A new
                # interrupt still takes precedence, retaining the earlier error
                # as its context through the same exception owner above.
                remember(exc);code=7
    if isinstance(pending,(KeyboardInterrupt,SystemExit)):raise pending
    return code
